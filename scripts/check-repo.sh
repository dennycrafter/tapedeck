#!/usr/bin/env bash
# Repo hygiene check (SPEC 9 T7). Run from anywhere: bash scripts/check-repo.sh
# Fails (exit 1) when a tracked file:
#   - contains an Anthropic key prefix (sk-ant-) or a Google key prefix (AIza)
#     (SPEC.md and .env.example files only describe the formats), a
#     64-character hex string outside .env.example files, or the R2 key
#     values (when R2_ACCESS_KEY_ID / R2_SECRET_ACCESS_KEY are set here);
#   - is audio, other than the two test tones;
#   - contains an en dash (U+2013) or em dash (U+2014). SPEC.md (the build
#     spec, kept as written) and web/AGENTS.md (regenerated by Next.js) are
#     left out;
# or when LICENSE is missing or README.md lacks one of the 7 SPEC 11 sections.
set -u
cd "$(git rev-parse --show-toplevel)" || exit 1
export LC_ALL=C   # byte-exact matching, whatever the machine's locale
fail=0
problem() { echo "FAIL: $*"; fail=1; }

# SPEC.md and the .env.example files document the key formats; they hold no keys.
hits=$(git grep -nI -e 'sk-ant-' -e 'AIza' -- . ':!scripts/check-repo.sh' ':!SPEC.md' ':!*.env.example' || true)
[ -n "$hits" ] && problem "API key prefixes in tracked files:" && echo "$hits"

hits=$(git grep -nIE '(^|[^0-9a-fA-F])[0-9a-fA-F]{64}([^0-9a-fA-F]|$)' -- . ':!*.env.example' ':!**/package-lock.json' || true)
[ -n "$hits" ] && problem "64-character hex strings in tracked files:" && echo "$hits"

for name in R2_ACCESS_KEY_ID R2_SECRET_ACCESS_KEY; do
  value="${!name:-}"
  if [ -n "$value" ] && git grep -qIF -e "$value" -- .; then problem "the $name value is in a tracked file"; fi
done

audio=$(git ls-files | grep -iE '\.(m4a|mp3|webm|opus|wav|aac|flac|ogg)$' | grep -vxE 'web/public/test-audio/test[12]\.m4a' || true)
[ -n "$audio" ] && problem "audio files tracked (only the two test tones are allowed):" && echo "$audio"

hits=$(git grep -nI -e $'\xe2\x80\x93' -e $'\xe2\x80\x94' -- . ':!SPEC.md' ':!web/AGENTS.md' || true)
[ -n "$hits" ] && problem "en or em dashes in tracked text files:" && echo "$hits"

[ -f LICENSE ] || problem "LICENSE is missing"

for section in "## 1. What Tapedeck is" "## 2. One-time setup" "## 3. PC downloader" "## 4. iPhone" "## 5. Daily use" "## 6. Apple Music" "## 7. Not working?"; do
  grep -qF "$section" README.md || problem "README.md is missing the section \"$section\""
done
grep -qF "Tapedeck ships no music. You are responsible for following the terms of the sites you use." README.md \
  || problem "README.md is missing the personal-use note"

if [ "$fail" -eq 0 ]; then echo "check-repo: all checks passed"; fi
exit "$fail"
