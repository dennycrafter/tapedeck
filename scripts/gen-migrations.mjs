// Embed supabase/migrations/*.sql into web/lib/migrations-sql.ts (T9).
//
// The migrations live outside the web/ build root, so Vercel would not
// bundle them with the functions that run them; the SQL travels inside the
// app instead, like schema-sql.ts does for schema.sql. A drift test
// (web/lib/migrations.test.ts) fails when the two disagree.
//
// Run from web/: npm run gen:migrations
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(repoRoot, 'supabase', 'migrations')
const out = path.join(repoRoot, 'web', 'lib', 'migrations-sql.ts')

const names = readdirSync(dir).filter((name) => name.endsWith('.sql')).sort()
const entries = names.map((name) => {
  const sql = readFileSync(path.join(dir, name), 'utf8').replaceAll('\r\n', '\n')
  return `  {\n    name: ${JSON.stringify(name)},\n    sql: ${JSON.stringify(sql)},\n  },\n`
})

const text = `/**
 * The files in supabase/migrations, embedded so the deployed app can run
 * them (T9, see lib/migrations.ts). Generated by scripts/gen-migrations.mjs:
 * add a .sql file there, then run \`npm run gen:migrations\` in web/.
 * Do not edit by hand; migrations.test.ts fails when this drifts.
 */
export const MIGRATION_FILES: readonly { name: string; sql: string }[] = [
${entries.join('')}]
`
writeFileSync(out, text)
console.log(`gen-migrations: wrote ${names.length} migration(s) to web/lib/migrations-sql.ts`)
